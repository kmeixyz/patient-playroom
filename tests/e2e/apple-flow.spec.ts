import { test, expect } from '@playwright/test'
import AxeBuilder from '@axe-core/playwright'

test('start is visible before optional setup and replay creates a fresh round', async ({ page }) => {
  await page.goto('/')
  await page.getByRole('button', { name: 'Play Bubble Pop', exact: true }).click()
  await expect(page.locator('.game-options')).not.toHaveAttribute('open', '')
  await expect(page.getByRole('button', { name: 'Start playing', exact: true })).toBeInViewport()
  await page.getByRole('button', { name: 'Start playing', exact: true }).click()
  for (let i = 1; i <= 12; i++) await page.getByRole('button', { name: `Pop bubble ${i}`, exact: true }).click()
  await page.getByRole('button', { name: 'All done', exact: true }).click()
  await page.getByRole('button', { name: 'Play again', exact: true }).click()
  await expect(page.locator('.bubble-count')).toHaveText('0 / 12')
  await expect(page.getByRole('button', { name: 'Pop bubble 1', exact: true })).toBeFocused()
  const stats = await page.evaluate(() => JSON.parse(localStorage.getItem('mvp.pilot.v1')!).games.bubbles)
  expect(stats.starts).toBe(2); expect(stats.finishes).toBe(1)
})

